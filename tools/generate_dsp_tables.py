"""Generate mathematical constants for the firmware FSK interpolator."""
from pathlib import Path
import numpy as np
root=Path(__file__).resolve().parents[1]
pulse=np.exp(-np.linspace(-3,3,17)**2)
n=np.arange(-7,8);fir=.15*np.sinc(.15*n)*np.hamming(15);fir/=fir.sum()
n=np.arange(-240,241);kernel=np.sinc(n/20)*np.kaiser(len(n),8.6)
out='/* SPDX-License-Identifier: GPL-3.0-or-later; generated by tools/generate_dsp_tables.py */\n'
for name,values in [('pulse',pulse),('fir',fir),('sinc',kernel)]:
    out+=f'static const double dsp_{name}[{len(values)}]={{\n'
    out+=',\n'.join(','.join(f'{v:.17g}' for v in values[i:i+6]) for i in range(0,len(values),6))+'\n};\n'
(root/'components/godox_waveform/dsp_tables.h').write_text(out,encoding='utf-8')
